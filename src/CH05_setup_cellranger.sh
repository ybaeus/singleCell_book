#!/bin/bash
# 챕터 05 셀 레인저 설치 - 다운로드 및 압축 해제 명령어 모음
#
# 이 파일은 한 번에 실행하는 스크립트가 아니라, 책 챕터 05에 나오는
# 터미널 명령어를 모아둔 참고용 파일입니다.
#
# 셀 레인저와 참조서열은 10x Genomics 다운로드 센터에서 직접 내려받아야 합니다.
# 로그인 및 약관 동의가 필요하고 내려받기 주소가 매번 새로 만들어지기 때문에
# 고정된 다운로드 명령어를 여기에 적어둘 수 없습니다.
#
#   다운로드 센터
#   10xgenomics.com/support/software/cell-ranger/downloads/previous-versions
#
#   버전별 업데이트 내용(릴리즈 노트)
#   10xgenomics.com/support/software/cell-ranger/latest/release-notes/cr-release-notes
#
# 이 책은 셀 레인저 v10.1.0과 인간 참조서열 GRCh38(refdata-gex-GRCh38-2024-A)을
# 기준으로 합니다.

# ---------------------------------------------------------------
# [1] 셀 레인저 내려받기 ([그림 5-2] 셀 레인저 다운로드 센터)
# ---------------------------------------------------------------
# 다운로드 센터에서 <Download for Linux 64-bit (tar.gz)> 버튼을 클릭하거나,
# 버튼 아래에 표시되는 curl 또는 wget 명령어를 복사해 아래에 붙여넣고 실행하세요.
#
# curl -o cellranger-10.1.0.tar.gz "https://cf.10xgenomics.com/releases/cell-exp/..."

# ---------------------------------------------------------------
# [코드 5-1] 셀 레인저 tar 파일 해제
# ---------------------------------------------------------------
# 내려받은 셀 레인저 버전에 맞게 파일 이름을 바꿔주세요.
tar -xzvf cellranger-10.1.0.tar.gz

# ---------------------------------------------------------------
# [2] 참조서열 내려받기 ([그림 5-4] 셀 레인저 전용 표준 염기서열 다운로드 화면)
# ---------------------------------------------------------------
# 같은 다운로드 센터 페이지에서 스크롤을 내리면 인간(GRCh38)과 쥐(GRCm39)
# 참조서열을 내려받을 수 있습니다. 여기서도 페이지에 표시되는 curl 또는 wget
# 명령어를 복사해 아래에 붙여넣고 실행하세요.
#
# curl -o refdata-gex-GRCh38-2024-A.tar.gz "https://cf.10xgenomics.com/supp/cell-exp/..."

# ---------------------------------------------------------------
# [코드 5-2] GRCh38 참조서열 tar 파일 해제
# ---------------------------------------------------------------
tar -xvzf refdata-gex-GRCh38-2024-A.tar.gz
rm refdata-gex-GRCh38-2024-A.tar.gz # 압축 파일 삭제
