#!/bin/bash
# 챕터 04 시퀀싱 데이터 다운로드 - 환경 설정 명령어 모음
#
# 이 파일은 한 번에 실행하는 스크립트가 아니라, 책 챕터 04에 나오는
# 터미널 명령어를 모아둔 참고용 파일입니다.
# 사용하는 운영체제에 맞는 줄만 골라서 터미널에 붙여넣어 실행하세요.

# ---------------------------------------------------------------
# [코드 4-1] SRA-Toolkit 다운로드 및 압축 해제
# ---------------------------------------------------------------
# macOS
curl --output sratoolkit.tar.gz https://ftp-trace.ncbi.nlm.nih.gov/sra/sdk/current/sratoolkit.current-mac-arm64.tar.gz

# 우분투(리눅스) 기반
wget --output-document sratoolkit.tar.gz https://ftp-trace.ncbi.nlm.nih.gov/sra/sdk/current/sratoolkit.current-ubuntu64.tar.gz

# 압축 해제
tar -vxzf sratoolkit.tar.gz

# ---------------------------------------------------------------
# [코드 4-2] macOS 환경에서 Homebrew 설치하기
# ---------------------------------------------------------------
/bin/bash -c "$(curl -fsSL https://raw.githubusercontent.com/Homebrew/install/HEAD/install.sh)"

# 확인하기
which brew

# ---------------------------------------------------------------
# [코드 4-3] 여러 환경에서 wget 설치하기
# ---------------------------------------------------------------
# macOS
brew install wget

# 우분투(리눅스) 기반(sudo는 관리자 권한을 의미하며, 관리자 비밀번호를 입력해야 합니다)
sudo apt install wget

# ---------------------------------------------------------------
# [코드 4-4] SRA-Toolkit 실행 파일 경로 설정
# ---------------------------------------------------------------
# 내려받은 SRA-Toolkit 버전에 맞게 폴더 이름을 바꿔주세요.
# macOS
export PATH="$PWD/sratoolkit.3.2.1-mac64/bin:$PATH"

# 리눅스 기반
export PATH="$PWD/sratoolkit.3.2.1-ubuntu64/bin:$PATH"

# ---------------------------------------------------------------
# [코드 4-5] fasterq-dump로 샘플 하나만 내려받기
# ---------------------------------------------------------------
fasterq-dump SRR13911909 -O ../data/SRR13911909

# ---------------------------------------------------------------
# [코드 4-6] pigz 설치(멀티스레드 압축용)
# ---------------------------------------------------------------
# macOS
brew install pigz

# 우분투(리눅스) 기반
sudo apt install pigz

# ---------------------------------------------------------------
# [코드 4-7] 전체 샘플 다운로드 스크립트 실행
# ---------------------------------------------------------------
bash CH04_sra_download.sh
